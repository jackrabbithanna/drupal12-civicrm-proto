#!/usr/bin/env bash
#
# Shared helpers for the civicrm_entity upgrade test harness.
#
#   source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
#
# Sourced, never executed. Loading it twice is a no-op. It defines the logging
# helpers, the DRY_RUN-aware `run` family every script issues its state-changing
# commands through, and the small lookups (module version, latest checkpoint,
# JSON key, drush command probe) the orchestration scripts share.
#
# The `run` family:
#   run <argv...>              echo, then run unless DRY_RUN=1
#   run_sh '<shell string>'    echo, then eval unless DRY_RUN=1 (pipes/redirects)
#   run_tee <log> <argv...>    echo, then run with 2>&1 | tee -a <log>; returns
#                              the command's status, never the tee's
#   run_capture <file> <argv>  echo, then run with stdout > <file>
#   ro <argv...>               echo, then run ALWAYS -- read-only commands, so
#                              a dry run still resolves paths and versions
#   run_script <script> [args] echo, then run ALWAYS -- the child script honours
#                              DRY_RUN itself and expands its own trace
#
# run_tee and run_capture never abort the caller: they return the command's
# exit code so a stage can be recorded as failed and the run can continue.

if [[ -n "${_CE_UPGRADE_LIB_LOADED:-}" ]]; then
  return 0
fi
_CE_UPGRADE_LIB_LOADED=1

# ---------------------------------------------------------------- logging ---

log() { printf '%s\n' "$*" >&2; }

die() { printf '\nerror: %s\n' "$*" >&2; exit 1; }

step() {
  printf '\n=== %s  %s ===\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" >&2
}

# Quotes an argv for display so the echoed line can be pasted back into a shell.
_quote() {
  local out='' arg
  for arg in "$@"; do
    if [[ "$arg" =~ ^[A-Za-z0-9_@%+=:,./-]+$ ]]; then
      out+="$arg "
    else
      out+="'${arg//\'/\'\\\'\'}' "
    fi
  done
  printf '%s' "${out% }"
}

# Keeps the database password out of the echoed command lines and the logs.
_redact() {
  printf '%s' "$1" | sed -E -e "s/'--password=[^']*'/'--password=***'/g" \
                            -e "s/--password=[^[:space:]']*/--password=***/g"
}

# ------------------------------------------------------------ run wrappers ---

run() {
  printf '  + %s\n' "$(_redact "$(_quote "$@")")" >&2
  if [[ "${DRY_RUN:-0}" == "1" ]]; then
    return 0
  fi
  "$@"
}

# Read-only: echoed and always executed, dry run included.
ro() {
  printf '  + %s\n' "$(_redact "$(_quote "$@")")" >&2
  "$@"
}

run_sh() {
  printf '  + %s\n' "$(_redact "$1")" >&2
  if [[ "${DRY_RUN:-0}" == "1" ]]; then
    return 0
  fi
  eval "$1"
}

# Runs a command with its combined output appended to a log file. Returns the
# command's exit status (not tee's) and never trips the caller's `set -e`.
run_tee() {
  local logfile="$1"
  shift
  printf '  + %s 2>&1 | tee -a %s\n' "$(_redact "$(_quote "$@")")" "$logfile" >&2
  if [[ "${DRY_RUN:-0}" == "1" ]]; then
    return 0
  fi
  local had_e=0
  [[ $- == *e* ]] && had_e=1
  set +e
  "$@" 2>&1 | tee -a "$logfile"
  local rc=${PIPESTATUS[0]}
  [[ $had_e == 1 ]] && set -e
  return "$rc"
}

# Runs a command with stdout redirected to a file. Same contract as run_tee.
run_capture() {
  local outfile="$1"
  shift
  printf '  + %s > %s\n' "$(_redact "$(_quote "$@")")" "$outfile" >&2
  if [[ "${DRY_RUN:-0}" == "1" ]]; then
    return 0
  fi
  local had_e=0
  [[ $- == *e* ]] && had_e=1
  set +e
  "$@" > "$outfile"
  local rc=$?
  [[ $had_e == 1 ]] && set -e
  return "$rc"
}

# Invokes another script in this harness. Those scripts are DRY_RUN aware
# themselves, so this always executes: a dry run then prints the whole expanded
# command sequence instead of a list of script names.
run_script() {
  printf '  > %s\n' "$(_redact "$(_quote "$@")")" >&2
  "$@"
}

# ------------------------------------------------------------------ checks ---

require_dir() {
  [[ -d "$1" ]] || die "${2:-required directory is missing}: $1"
}

require_file() {
  [[ -f "$1" ]] || die "${2:-required file is missing}: $1"
}

# A config set root has to carry all three of these for the import path to mean
# anything. Under DRY_RUN this warns instead of dying, because the set is
# generated by an earlier step of the very run being rehearsed.
set_root_check() {
  local root="$1"
  local missing=()
  [[ -d "$root/portable" ]] || missing+=('portable/')
  [[ -f "$root/settings/civicrm_entity.settings.yml" ]] || missing+=('settings/civicrm_entity.settings.yml')
  [[ -f "$root/MANIFEST.json" ]] || missing+=('MANIFEST.json')
  if [[ ${#missing[@]} -gt 0 ]]; then
    if [[ "${DRY_RUN:-0}" == "1" ]]; then
      log "  warning: $root is not a config set root yet (missing: ${missing[*]}) -- tolerated in a dry run"
      return 0
    fi
    die "$root is not a config set root; missing: ${missing[*]}"
  fi
}

# ----------------------------------------------------------------- lookups ---

# Prints the version of the module installed at $MODULE_DST (or $1).
# 5.0.x is unreleased and carries no packaged version line, so it is identified
# by src/Api, the directory the API gateway rewrite added.
module_version() {
  local dir="${1:-$MODULE_DST}"
  if [[ -d "$dir/src/Api" ]]; then
    printf '5.0.x\n'
    return 0
  fi
  local info="$dir/civicrm_entity.info.yml"
  if [[ ! -f "$info" ]]; then
    printf 'unknown\n'
    return 0
  fi
  local version
  version=$(sed -n "s/^version:[[:space:]]*['\"]\{0,1\}\([^'\"[:space:]]*\)['\"]\{0,1\}.*/\1/p" "$info" | head -n 1)
  printf '%s\n' "${version:-unknown}"
}

# Newest checkpoint JSON in $RUN, ignoring the per-stage side files.
latest_checkpoint_json() {
  local found
  found=$(
    find "$RUN" -maxdepth 1 -type f -name '*.json' -printf '%T@ %p\n' 2>/dev/null \
      | sort -rn \
      | cut -d' ' -f2- \
      | grep -Ev -- '-(audit[^/]*|plan|apply|parity)\.json$' \
      | head -n 1
  ) || true
  printf '%s' "$found"
}

# json_get <file> <dotted.key> -- prints the value, or nothing if absent.
json_get() {
  local file="$1" key="$2"
  [[ -f "$file" ]] || return 0
  php -r '
    $data = json_decode(file_get_contents($argv[1]), TRUE);
    foreach (explode(".", $argv[2]) as $part) {
      if (!is_array($data) || !array_key_exists($part, $data)) { exit; }
      $data = $data[$part];
    }
    echo is_scalar($data) ? $data : json_encode($data);
  ' "$file" "$key" 2>/dev/null || true
}

# True when the site's drush knows the named command.
drush_has_command() {
  local name="$1" listing
  listing=$("${DRUSH[@]}" list --format=json 2>/dev/null) || listing=''
  if [[ -n "$listing" ]] && printf '%s' "$listing" | grep -q "\"name\":\"$name\""; then
    return 0
  fi
  "${DRUSH[@]}" list 2>/dev/null | grep -qE "(^|[[:space:]])${name}([[:space:]]|$)"
}
